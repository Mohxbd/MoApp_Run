import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
const cors = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Headers": "authorization, apikey, content-type", "Access-Control-Allow-Methods": "POST, OPTIONS", "Content-Type": "application/json" };
const json = (body: unknown, status=200) => new Response(JSON.stringify(body), {status, headers:cors});
const hex = (bytes: Uint8Array) => [...bytes].map(b=>b.toString(16).padStart(2,"0")).join("");
Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok",{headers:cors});
  if (req.method !== "POST") return json({error:"Méthode non autorisée"},405);
  const auth = req.headers.get("Authorization") || "";
  const client = createClient(Deno.env.get("SUPABASE_URL")!, Deno.env.get("SUPABASE_ANON_KEY")!, {global:{headers:{Authorization:auth}}});
  const {data:{user},error} = await client.auth.getUser();
  if (error || !user) return json({error:"Authentification requise"},401);
  const clientId = Deno.env.get("STRAVA_CLIENT_ID"), redirect = Deno.env.get("STRAVA_REDIRECT_URI");
  if (!clientId || !redirect) return json({error:"Configuration Strava incomplète"},500);
  const service = createClient(Deno.env.get("SUPABASE_URL")!, Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!);
  const state = hex(crypto.getRandomValues(new Uint8Array(32)));
  const stateHash = hex(new Uint8Array(await crypto.subtle.digest("SHA-256",new TextEncoder().encode(state))));
  const {error:insertError} = await service.from("strava_oauth_states").insert({state_hash:stateHash,user_id:user.id,expires_at:new Date(Date.now()+10*60*1000).toISOString()});
  if(insertError) return json({error:"Impossible d'initialiser OAuth"},500);
  const url = new URL("https://www.strava.com/oauth/authorize");
  url.search = new URLSearchParams({client_id:clientId,response_type:"code",redirect_uri:redirect,approval_prompt:"auto",scope:"read,activity:read_all",state}).toString();
  return json({url:url.toString()});
});
